"""Suggest a --reference_frame per episode: early, stable, with both hands clearly visible.

The baseline seeds every hand and object track on the reference frame and stops if no hand is
found there, so frame 0 is often a poor choice. This scans each ego_cam_a video with MediaPipe's
hand landmarker (CPU). Recordings open with both hands raised, so it picks the frame with the most (and
most confident) detected hands within the first WINDOW frames. MediaPipe is a proxy: the pipeline itself
detects hands with WiLoR, and object visibility is not checked here.

Writes tools/track3/reference_frames.json, read by run_baseline_reconstruction.py.

    uv run --no-project --python 3.11 --with mediapipe==0.10.18 --with opencv-python-headless \
        python tools/track3/suggest_reference_frames.py [--episodes 1 3] [--workers 8]
"""
from __future__ import annotations

import argparse
import json
import urllib.request
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MANIFEST = Path(__file__).with_name("episodes.json")
OUT = Path(__file__).with_name("reference_frames.json")
# Same model file NVIDIA's v2d_mediapipe image bakes in.
MODEL_URL = ("https://storage.googleapis.com/mediapipe-models/hand_landmarker/hand_landmarker/float16/1/"
             "hand_landmarker.task")
STRIDE = 2           # analyse every 2nd frame
MIN_SCORE = 0.5      # detection confidence for a hand to count
WINDOW = 90          # recordings open with both hands raised within the first ~4.5 s
SKIP = 3             # ignore the first frames (exposure settling)


def model_path(cache: Path) -> Path:
    path = cache / "hand_landmarker.task"
    if not path.is_file():
        cache.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(MODEL_URL, path)
    return path


def hand_scores(result) -> list[float]:
    # Count hands only: MediaPipe's handedness labels assume a selfie view and are unreliable
    # on egocentric frames. It often misses one of two hands near the fisheye image edges.
    return sorted((h[0].score for h in result.handedness if h[0].score >= MIN_SCORE), reverse=True)


def analyse(episode: dict, model: str) -> dict:
    import cv2
    import mediapipe as mp
    from mediapipe.tasks.python import BaseOptions
    from mediapipe.tasks.python.vision import HandLandmarker, HandLandmarkerOptions, RunningMode

    options = HandLandmarkerOptions(base_options=BaseOptions(model_asset_path=model), num_hands=2,
                                    min_hand_detection_confidence=0.5, running_mode=RunningMode.IMAGE)
    video = cv2.VideoCapture(str(REPO / episode["video"]))
    flags, frame = [], 0
    with HandLandmarker.create_from_options(options) as detector:
        while True:
            ok, bgr = video.read()
            if not ok:
                break
            if frame % STRIDE == 0:
                small = cv2.resize(bgr, None, fx=0.5, fy=0.5, interpolation=cv2.INTER_AREA)
                image = mp.Image(image_format=mp.ImageFormat.SRGB, data=cv2.cvtColor(small, cv2.COLOR_BGR2RGB))
                flags.append((frame, hand_scores(detector.detect(image))))
            frame += 1
    # Most hands, then highest total confidence, then earliest, within the opening window.
    window = [(n, s) for n, s in flags if SKIP <= n < WINDOW] or [(n, s) for n, s in flags if n >= SKIP]
    best_frame, best = max(window, key=lambda item: (len(item[1]), sum(item[1]), -item[0]))
    return {"episode": episode["episode"], "split": episode["split"], "suggested": best_frame,
            "hands_at_suggested": len(best), "score_at_suggested": round(sum(best), 3),
            "two_hand_fraction": round(sum(len(s) >= 2 for _, s in flags) / max(len(flags), 1), 3)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--episodes", type=int, nargs="*")
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--cache", type=Path, default=Path.home() / ".cache/v2d_t3")
    args = parser.parse_args()
    episodes = [e for e in json.loads(MANIFEST.read_text())["episodes"]
                if not args.episodes or e["episode"] in args.episodes]
    model = str(model_path(args.cache))
    with ProcessPoolExecutor(max_workers=args.workers) as pool:
        results = list(pool.map(analyse, episodes, [model] * len(episodes)))
    existing = json.loads(OUT.read_text())["episodes"] if OUT.is_file() else {}
    existing.update({str(r["episode"]): r for r in results})
    OUT.write_text(json.dumps({"_comment": [
        "Generated by tools/track3/suggest_reference_frames.py (MediaPipe proxy for WiLoR).",
        "Override per run with --reference-frame if the baseline cannot detect a hand or the object.",
    ], "episodes": dict(sorted(existing.items(), key=lambda kv: int(kv[0])))}, indent=1) + "\n")
    for r in results:
        print(f"{r['split']:<10} ep{r['episode']:>3}  frame {r['suggested']:>3}  "
              f"hands {r['hands_at_suggested']} (score {r['score_at_suggested']:.2f})  "
              f"two-hand frames {r['two_hand_fraction']:.0%}")


if __name__ == "__main__":
    main()
