"""Build tools/track3/episodes.json: one entry per Track 3 episode (public + evaluation).

For every episode it records the split, frame count, ego_cam_a video path, and the ordered
object list with a detection prompt per object. Public episodes also get per-object
visibility from the ground truth. Evaluation object order comes from the submission kit
(it is the object_slot order the scorer uses, and not always sorted by name).

Run from the repo root:
    uv run --project tools python tools/track3/build_manifest.py
"""
import json
import subprocess
from pathlib import Path

import pyarrow.parquet as pq

REPO = Path(__file__).resolve().parents[2]
DATA = REPO / "assets/data/track_3"
KIT = REPO / "assets/data/v2d_submission_kit"
OUT = Path(__file__).with_name("episodes.json")

# Grounding DINO text prompt per object. Colour + noun matches what is visible in the
# ego_cam_a frames; review these if detection picks the wrong object.
PROMPTS = {
    "beige_cup": "beige cup",
    "blue_cup": "blue cup",
    "mini_dust_pan": "yellow dust pan",
    "mini_sweeper": "small yellow brush",
    "plastic_dish_rack": "white dish rack",
    "water_pitcher": "white watering pitcher",
    "white_pot": "white pot",
    "white_pot_lid": "white pot lid",
    "wooden_piece_1": "wooden board",
    "wooden_piece_2": "wooden board",
    "wooden_spoon": "wooden spoon",
}

VIDEO = "videos/chunk-000/observation.images.ego_cam_a/episode_{:06d}.mp4"


def video_frames(path: Path) -> int:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v:0", "-count_packets",
         "-show_entries", "stream=nb_read_packets", "-of", "csv=p=0", str(path)],
        check=True, capture_output=True, text=True,
    )
    return int(out.stdout.strip())


def scanned_objects() -> set[str]:
    return {p.name for p in (DATA / "public/mesh").iterdir() if p.is_dir()}


def public_episodes(scans: set[str]) -> list[dict]:
    info = json.loads((DATA / "public/meta/info.json").read_text())
    tasks = {
        e["episode_index"]: e["task"]
        for e in map(json.loads, (DATA / "public/meta/episodes_metadata.jsonl").read_text().splitlines())
    }
    episodes = []
    for ep in info["episode_indices"]:
        table = pq.read_table(DATA / f"public/data/chunk-000/episode_{ep:06d}.parquet")
        rows = table.column("observation.objects").to_pylist()
        # The per-frame order is authoritative. In episodes 11 and 18 it is the reverse of
        # the schema metadata's `objects` list, despite the dataset card, so never index
        # objects by the metadata's position.
        names = [o["name"] for o in rows[0]]
        assert all([o["name"] for o in frame] == names for frame in rows), ep
        assert sorted(names) == sorted(json.loads(table.schema.metadata[b"objects"])), ep
        objects = []
        for slot, name in enumerate(names):
            vis = [frame[slot]["visible"] for frame in rows]
            seen = [i for i, v in enumerate(vis) if v]
            objects.append({
                "name": name,
                "prompt": PROMPTS[name],
                "has_public_scan": name in scans,
                "gt_visible_fraction": round(len(seen) / len(vis), 3),
                "gt_first_visible": seen[0] if seen else None,
                "gt_last_visible": seen[-1] if seen else None,
            })
        video = DATA / "public" / VIDEO.format(ep)
        n_video = video_frames(video)
        assert n_video == len(rows), (ep, n_video, len(rows))
        episodes.append({
            "split": "public",
            "episode": ep,
            "task": tasks.get(ep),
            "num_frames": len(rows),
            "video": str(video.relative_to(REPO)),
            "objects": objects,
        })
    return episodes


def evaluation_episodes(scans: set[str]) -> list[dict]:
    roster = json.loads((KIT / "data/track_3_evaluation_objects.json").read_text())["episodes"]
    episodes = []
    for ep_str, names in sorted(roster.items(), key=lambda kv: int(kv[0])):
        ep = int(ep_str)
        video = DATA / "evaluation" / VIDEO.format(ep)
        episodes.append({
            "split": "evaluation",
            "episode": ep,
            "task": None,
            "num_frames": video_frames(video),
            "video": str(video.relative_to(REPO)),
            "objects": [
                {"name": n, "prompt": PROMPTS[n], "has_public_scan": n in scans} for n in names
            ],
        })
    return episodes


def main() -> None:
    scans = scanned_objects()
    episodes = public_episodes(scans) + evaluation_episodes(scans)
    manifest = {
        "_comment": [
            "Generated by tools/track3/build_manifest.py; edit PROMPTS there, not here.",
            "Object order is the per-frame order (= object_slot); for public eps 11 and 18 it differs from the parquet metadata. Frames are already upright.",
            "reference_frame is chosen per episode later (hands + objects visible).",
        ],
        "episodes": episodes,
    }
    OUT.write_text(json.dumps(manifest, indent=1) + "\n")
    n_obj = sum(len(e["objects"]) for e in episodes if e["split"] == "evaluation")
    print(f"wrote {OUT.relative_to(REPO)}: {len(episodes)} episodes, {n_obj} evaluation (episode, object) pairs")


if __name__ == "__main__":
    main()
