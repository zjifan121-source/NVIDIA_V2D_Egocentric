FALSE_GRASP_CM = 12.0  # attach reach; a hand whose PRE-attach wrist-to-surface median over the lifted frames exceeds it only passed by
# fork 2 audit (2026-11-04 05:10 UTC) of the raw-hand exclusive re-attach; used only when no attach record is reachable
AUDIT_FALSE_GRASP = {14: ['left'], 15: ['left', 'right'], 16: ['left'], 28: ['left']}

def isf(p):
    try: return Path(p).is_file()
    except OSError: return False  # e.g. a /root path recorded by another host

def rd(p):
    try: return json.loads(Path(p).read_text())
    except Exception: return None

def attach_record(ep, bundle, mode):
    """The exclusive-attach record of THIS hand mode: the scene's bundle, else the hand-stage bundles dir of the same mode
    (rawspin uses attach_exclusive's assignment, so the rawexcl record is valid for it; never mix raw and Ken hands)."""
    hs = Path(os.environ.get('LEAD_HAND_BUNDLES', str(Path(os.environ.get('V2D_ROOT', '/Volumes/E/Code/V2D')) / 'NVIDIA_V2D_Egocentric' / HR / 'bundles')))
    dirs = ([Path(bundle)] if bundle else []) + [hs / f'ep{int(ep):02d}_{m}' for m in {'rawspin': ('rawspin', 'rawexcl')}.get(mode, (mode,))]
    for d in dirs:
        for f in ('ATTACH_EXCLUSIVE.json', 'ATTACH_RESPIN.json'):
            if isf(d / f): return d, f, rd(d / f) or {}
    return None, None, None

def false_grasp_hands(ep, bundle, mode):
    """attach_exclusive (and attach_respin, same math) glues a hand to an object for the WHOLE lifted segment once its min
    distance is within reach, so a hand that merely passed by is dragged onto the object; HAND_CONTACT (post-attach) cannot
    see this. Detected from the pre-attach medians in the attach record."""
    d, f, a = attach_record(ep, bundle, mode)
    if a is not None:
        names = None
        try:
            import numpy as np
            with np.load(d / 'result.npz', allow_pickle=False) as z:
                names = [str(n) for n in z['object_names']] if 'object_names' in z.files else None
        except Exception: pass
        out = []
        for obj, atts in (a.get('attached') or {}).items():
            i = int(obj.split('_')[-1]); oname = names[i] if names and i < len(names) else obj
            for side in sorted({x[0] for x in atts}):
                c = (a.get('candidates') or {}).get(f'{side}->object_{i}') or {}
                med = c.get('wrist_to_surface_median_cm')
                if med is not None and med > FALSE_GRASP_CM: out.append(dict(hand=side, object=oname, pre_attach_median_cm=med, min_cm=c.get('min_cm'), source=str(d / f)))
        return out, 'measured'
    if mode in ('rawexcl', 'rawspin') and int(ep) in AUDIT_FALSE_GRASP:
        return [dict(hand=h, object=None, pre_attach_median_cm=None, source='fork 2 audit 2026-11-04 05:10 UTC (no attach record reachable)') for h in AUDIT_FALSE_GRASP[int(ep)]], 'audit_list'
    return [], 'no_attach_record'

def release_gaps(bundle, ah):
    """Gaps attach_hold filled although the object stays put and the hand is tracked: a real release (object placed, e.g. in
    the rack, still 'lifted' by height), not the tracking miss the gap rule assumes. The hand is kept on a placed object."""
    out = []
    try:
        import numpy as np
        with np.load(Path(bundle) / 'result.npz', allow_pickle=False) as z:
            for g in ah.get('gaps_filled') or []:
                side = g.get('side'); a, b = g['frames']
                if side is None or b - a < 5: continue
                key = 'object_to_world_transform' if g['object'] == 0 else f"object_{g['object']}_to_world_transform"
                q = z[key][a:b, :3, 3].astype(float); net = float(np.linalg.norm(q[-1] - q[0])) * 100
                vk = f'hand_{side}_is_valid'; valid = float(np.mean(z[vk][a:b])) if vk in z.files else None
                if net < 1.0 and (valid is None or valid >= 0.9):
                    out.append(dict(object=g['object'], frames=[int(a), int(b)], hand=side, object_net_cm=round(net, 2), wrist_median_cm=g.get('median_cm'), hand_valid=valid))
    except Exception: pass
    return out

def provenance(scene: Path) -> dict:
    scene = Path(scene).resolve(); scripts, inputs, markers, notes = [], {}, [], []
    for m, s in SCENE_MARKERS.items():
        if isf(scene / m): markers.append(m); scripts += s
    if isf(scene / 'relocate.log'): markers.append('relocate.log'); notes.append('paths relocated with tools/track3/relocate_scene.py (Edmond, in de66fea3)')
    check = rd(scene / 'OUTPUT_CHECK.json') or {}
    mode = check.get('mode'); inputs['hands_mode'] = mode; inputs['hands'] = HANDS.get(mode); inputs['sequence_id'] = check.get('sequence_id')
    scripts += MODE_SCRIPTS.get(mode, [])
    # bundle: the path OUTPUT_CHECK recorded (may belong to the builder machine), else the episode_X/{bundle,scene} layout
    cands = ([Path(check['bundle_cleaned'])] if check.get('bundle_cleaned') else []) + [scene.parent / 'bundle', scene.parent / 'bundle_cleaned']
    bundle = next((b for b in cands if isf(b / 'result.npz')), None)
    inputs['bundle'] = str(bundle) if bundle else (check.get('bundle_cleaned') or None)
    if bundle is None and check.get('bundle_cleaned'): notes.append('bundle dir of the builder machine not reachable here; markers read from the scene only')
    ah = None
    if bundle:
        prep = rd(bundle / 'HANDFIX_PREP.json')
        if prep:
            markers.append('bundle/HANDFIX_PREP.json')
            inputs['objects_source_bundle'] = prep.get('source_bundle'); inputs['objects_hf_prefix'] = prep.get('hf_stage_prefix'); inputs['raw_hands_hf_path'] = prep.get('raw_hands_hf_path')
        for f in ('ATTACH_EXCLUSIVE.json', 'ATTACH_RESPIN.json', 'ATTACH_HOLD.json'):
            if isf(bundle / f): markers.append(f'bundle/{f}')
        if isf(bundle / 'MESH_POSE_PAIR.json'): markers.append('bundle/MESH_POSE_PAIR.json'); scripts.append('work/lead-sprint-release-20261103/build_stage.py (lead_sprint_v1 objects: fb11 + replaced meshes/tracks)')
        if isf(bundle / 'manifest.json'): markers.append('bundle/manifest.json')
        ah = rd(bundle / 'ATTACH_HOLD.json') if isf(bundle / 'ATTACH_HOLD.json') else None
    prov = rd(scene.parent / 'PROVENANCE.json')
    if prov:
        markers.append('../PROVENANCE.json'); scripts.append('work/lead-v3-release-20261104/build_v3.py (lead_v3: v1 objects + matched hands written into bundle/result.npz + seated support)')
        inputs['lead_v3'] = {k: prov.get(k) for k in ('objects_version', 'objects_changed_vs_fb11') if k in prov}
        h = prov.get('hands') if isinstance(prov.get('hands'), dict) else None
        if h: inputs['lead_v3']['hands_source'] = h.get('source'); inputs['lead_v3']['hands_rule'] = h.get('rule')
        if mode is None and h and h.get('source'): inputs['hands'] = h.get('source')
        if 'exclusive re-attach' in ((h or {}).get('source') or ''):  # build_v3 copied hands made by the hand stage
            scripts += [f'{HR}/compare_hands.py', f'{HR}/hand_ledger.py']
    sp = str(scene); src_bundle = str(inputs.get('objects_source_bundle') or '')
    v8 = any(t in sp for t in ('lead_winners_v8', 'v8pot', 'newpot', 'handspin28')) or any(t in src_bundle for t in ('lead_winners_v8', 'recovery_cont_donor'))
    if v8:
        scripts += [f'{OPS}/lead_retrack_recovery_v8/build_cases_v8.py', f'{OPS}/lead_retrack_recovery_v8/evaluate_remote.py', f'{OPS}/lead_retrack_recovery_v8/flatten_assets.py', f'{OPS}/lead_retrack_recovery_v8/flatten_host.py',
                    f'{OPS}/lead_retrack_recovery_v8/launch_batch.py (FoundationPose container v2d_foundation_pose:afe7dad-trt10.7 on the A6000)', f'{HR}/apply_winners_remote.py']
        notes.append('object track/mesh of the winning object re-tracked with a donor mesh (v8); see <winners_root>/winners.json and the candidate_bundle MESH_POSE_PAIR.json')
    if 'v8pot' in sp: scripts.append('work/lead-v3-ep28-release-20261104/build_ep28.py (HF overlay scored20_lead_v3_ep28pot_20261104)')
    scripts.append('upstream object reconstruction = fb11 (HF scored20_contactshape_proxy_mix_v1_20261103) and its path_a pipeline (FoundationPose container + metric_scene_refinement lib; lead to enumerate)')
    ep = check.get('episode') or (prov or {}).get('episode')
    if ep is None:
        mm = re.search(r'episode_(\d+)|/ep(\d+)_', sp); ep = int(next(g for g in mm.groups() if g)) if mm else None
    if ep is not None and mode in ('rawexcl', 'kenexcl', 'rawspin'):
        fg, how = false_grasp_hands(ep, bundle, mode); inputs['false_grasp_hands'] = fg; inputs['false_grasp_check'] = how
        if fg: notes.append('FALSE GRASP: ' + ', '.join(f"{x['hand']} hand on {x['object']} (pre-attach median {x['pre_attach_median_cm']} cm)" for x in fg) + '; the attach glued a passing hand for the whole lifted segment; attach_hold.py scenes supersede')
    elif mode == 'hold':
        inputs['false_grasp_hands'] = []; inputs['false_grasp_check'] = 'per_frame_hold'
        if ah:
            inputs['hands_source'] = ah.get('source'); inputs['hold_gaps_filled'] = ah.get('gaps_filled')
            inputs['hold_hand_moved_max_cm'] = {s: max(x['max'] for x in v) for s, v in (ah.get('hand_moved_cm') or {}).items() if v}
            if 'kenclean' in str(ah.get('source')): scripts.append(f'{HR}/prep_kenhands.py')
            inputs['hold_release_gaps'] = release_gaps(bundle, ah)
    else:
        inputs['false_grasp_hands'] = []; inputs['false_grasp_check'] = 'not_applicable'
    scene_type = 'lead_v3 stage scene' if prov else ('v8 winner scene' if v8 else ('hand-stage scene' if check else 'unknown'))
    return dict(scene=str(scene), type=scene_type, episode=ep, inputs=inputs, markers=markers, scripts=sorted(set(scripts)), team_code=TEAM_CODE, notes=notes)

if __name__ == '__main__':
    for a in sys.argv[1:]: print(json.dumps(provenance(Path(a)), indent=1))
